#!/usr/bin/env python3
"""
QEDOS Press production-key wiring test (docs/QEDOS_PRESS_PROD_KEY.md). Closes the gap documented
in docs/QEDOS_PRESS_ADMIN.md: qedos_press_pd's actual Ed25519 trust key is a compile-time Rust
constant that must now be explicitly set via QEDOS_PRESS_PROD=1 / QEDOS_PRESS_PROD_PUBKEY, never
silently defaulting to the dev key. Every key used here is a THROWAWAY TEST fixture generated by
tools/press-sign-offline.py into a scratch directory -- never printed in full, never treated as
real production material.

  PROD_001  build-time fail-closed: QEDOS_PRESS_PROD=1 with no QEDOS_PRESS_PROD_PUBKEY set -> the
            build refuses (non-zero exit), no image produced
  PROD_002  build-time fail-closed: QEDOS_PRESS_PROD_PUBKEY pointing at malformed (non-hex /
            wrong-length) content -> the build refuses
  PROD_003  build-time fail-closed: QEDOS_PRESS_PROD_PUBKEY byte-for-byte identical to the
            committed dev key -> the build explicitly refuses to use it in production
  PROD_004  a bundle correctly signed by the test production key is accepted: the booted image's
            qedos_press_pd logs a verified signature and serves the exact content over TLS1.3
  PROD_005  a bundle with a corrupted (bit-flipped) signature is rejected by qedos_press_pd
            itself, inside the booted image -- the seL4-side verifier is the actual final gate,
            independent of anything the host-side admin tool checked before the build
  PROD_006  a bundle validly signed by a DIFFERENT test keypair is rejected by qedos_press_pd
            itself (same mechanism, different scenario: right signature math, wrong key)
  PROD_007  a bundle signed by the EXISTING DEV key is rejected by qedos_press_pd when the image
            was built with a different (test-production) pubkey -- proves the dev key cannot
            work in a production-configured image
  PROD_008  host-side press-admin.py rejects a validly-signed but lower-generation bundle
            (rollback/replay protection) BEFORE any build is attempted -- demonstrates this
            specific protection lives at the host layer, not inside the seL4 image (which has no
            persistent storage and no generation concept of its own)
  PROD_009  the host-side generation state file survives a press-admin.py process restart
            (simulating a host reboot) and still rejects the same old generation afterward
  PROD_010  build-time self-check: the production pubkey fingerprint press-admin.py reports for
            a pubkey file matches the fingerprint scripts/build-sel4.sh printed for the same file
            during the PROD_004 build (host side and seL4 side agree on the same key)

Honest, explicitly NOT covered by this test (see docs/QEDOS_PRESS_PROD_KEY.md "What is NOT
verified"): secure boot of the loader/kernel/initrd chain itself, and rollback protection against
someone bypassing press-admin.py entirely and booting an old loader.img directly -- this
mechanism only protects press-admin.py's own accept-and-build pathway.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "tests"))
import test_sel4 as T  # reuse QEMU_LAUNCHER / read_serial / s_client_request helpers

PQ = ["-tls1_3", "-groups", "X25519MLKEM768"]
passed = []


def ok(name, msg):
    passed.append(name)
    print(f"PASS {name} {msg}")


def run_offline(*args):
    r = subprocess.run(
        [sys.executable, os.path.join(ROOT, "tools/press-sign-offline.py"), *args,
         "--yes-i-am-on-a-separate-machine"],
        capture_output=True, text=True,
    )
    assert r.returncode == 0, f"press-sign-offline.py failed:\n{r.stdout}\n{r.stderr}"
    return r.stdout


def build(env_extra, out_dir, qpr=None, expect_fail=False):
    env = dict(os.environ)
    env["PATH"] = os.path.join(ROOT, "third_party/venv/bin") + os.pathsep + env.get("PATH", "")
    env["QEDOS_PRESS"] = "1"
    env["QEDOS_OUT"] = out_dir
    if qpr:
        env["QEDOS_PRESS_QPR"] = qpr
    env.update(env_extra)
    r = subprocess.run([os.path.join(ROOT, "scripts/build-sel4.sh")], cwd=ROOT, env=env,
                        capture_output=True, text=True, timeout=300)
    if expect_fail:
        assert r.returncode != 0, f"expected build to fail closed, but it succeeded:\n{r.stdout[-2000:]}"
    else:
        assert r.returncode == 0, f"build failed:\n{r.stdout[-4000:]}\n{r.stderr[-4000:]}"
    return r.stdout + r.stderr


def boot(loader_img, serial_log, port, seconds="40"):
    """Starts QEMU and waits until the press-verification outcome has landed in the serial log.
    Returns (qemu_process, serial_text_so_far) -- the CALLER is responsible for terminating
    qemu_process (in a try/finally) once done issuing requests against it."""
    qemu = subprocess.Popen([T.QEMU_LAUNCHER, loader_img, serial_log,
                              f"hostfwd=tcp:127.0.0.1:{port}-10.0.2.15:8443", seconds])
    T.SERIAL_LOG = serial_log
    T.GUEST_PORT = port
    deadline = time.time() + 30
    while time.time() < deadline:
        s = T.read_serial()
        if "QEDOS_PRESS_PD: Ed25519 release signature verified" in s or \
           "QEDOS_PRESS_PD: FATAL" in s or "HTTP_PD: initialized" in s:
            break
        time.sleep(0.25)
    time.sleep(1.0)  # let any late boot-time log line land
    return qemu, T.read_serial()


def terminate(qemu):
    qemu.terminate()
    try:
        qemu.wait(timeout=10)
    except subprocess.TimeoutExpired:
        qemu.kill()


def main():
    tmproot = tempfile.mkdtemp(prefix="press-prodkey-test-")
    qs = os.path.join(ROOT, "build/qs/ws/target/release/qs")
    if not os.path.exists(qs):
        subprocess.run([os.path.join(ROOT, "scripts/qs-ws.sh"), "build", "--release", "-p", "pg-script-cli"], check=True)

    # -- throwaway TEST keys, scratch dir only, never printed, never treated as real ------------
    prod_seed = os.path.join(tmproot, "prod-seed.hex")
    prod_pub = os.path.join(tmproot, "prod-pub.hex")
    run_offline("keygen", "--qs", qs, "--out-seed", prod_seed, "--out-pub", prod_pub)

    other_seed = os.path.join(tmproot, "other-seed.hex")
    other_pub = os.path.join(tmproot, "other-pub.hex")
    run_offline("keygen", "--qs", qs, "--out-seed", other_seed, "--out-pub", other_pub)

    garbage_pub = os.path.join(tmproot, "garbage-pub.hex")
    with open(garbage_pub, "w") as f:
        f.write("not-valid-hex")

    dev_pub = os.path.join(ROOT, "config/keys/qedos-press-dev-pub.hex")
    same_as_dev_pub = os.path.join(tmproot, "same-as-dev-pub.hex")
    shutil.copy(dev_pub, same_as_dev_pub)

    content_dir = os.path.join(tmproot, "content")
    os.makedirs(content_dir)
    boot_marker = "<!doctype html><html><body><h1>PROD KEY BOOT TEST</h1></body></html>"
    with open(os.path.join(content_dir, "index.html"), "w") as f:
        f.write(boot_marker)

    bundle_good = os.path.join(tmproot, "good.qpr")
    run_offline("sign", "--qs", qs, "--seed", prod_seed, "--release", "1", "--out", bundle_good, content_dir)

    bundle_corrupt = os.path.join(tmproot, "corrupt.qpr")
    shutil.copy(bundle_good, bundle_corrupt)
    with open(bundle_corrupt, "r+b") as f:
        f.seek(-1, os.SEEK_END)
        last = f.read(1)
        f.seek(-1, os.SEEK_END)
        f.write(bytes([last[0] ^ 0xFF]))  # flip the final signature byte

    bundle_other_key = os.path.join(tmproot, "other-key.qpr")
    run_offline("sign", "--qs", qs, "--seed", other_seed, "--release", "1", "--out", bundle_other_key, content_dir)

    dev_seed = os.path.join(ROOT, "config/keys/qedos-press-dev-seed.hex")
    bundle_dev_signed = os.path.join(tmproot, "dev-signed.qpr")
    run_offline("sign", "--qs", qs, "--seed", dev_seed, "--release", "1", "--out", bundle_dev_signed, content_dir)

    # ---- PROD_001/002/003: build-time fail-closed cases ----
    out_fail = os.path.join(tmproot, "out-fail")
    env = dict(os.environ)
    env.pop("QEDOS_PRESS_PROD_PUBKEY", None)
    log = build({"QEDOS_PRESS_PROD": "1"}, out_fail, qpr=bundle_good, expect_fail=True)
    assert "requires QEDOS_PRESS_PROD_PUBKEY" in log, log[-1000:]
    ok("PROD_001", "QEDOS_PRESS_PROD=1 with no pubkey configured -> build refuses (fail closed)")

    log = build({"QEDOS_PRESS_PROD": "1", "QEDOS_PRESS_PROD_PUBKEY": garbage_pub}, out_fail,
                qpr=bundle_good, expect_fail=True)
    assert "must contain exactly 64 hex characters" in log, log[-1000:]
    ok("PROD_002", "malformed (non-hex) production pubkey -> build refuses (fail closed)")

    log = build({"QEDOS_PRESS_PROD": "1", "QEDOS_PRESS_PROD_PUBKEY": same_as_dev_pub}, out_fail,
                qpr=bundle_good, expect_fail=True)
    assert "identical to the committed dev key" in log, log[-1000:]
    ok("PROD_003", "production pubkey identical to the dev key -> build explicitly refuses")

    # ---- PROD_004: correct signature, correct key -> accepted and served ----
    out_good = os.path.join(tmproot, "out-good")
    log = build({"QEDOS_PRESS_PROD": "1", "QEDOS_PRESS_PROD_PUBKEY": prod_pub}, out_good, qpr=bundle_good)
    m = re.search(r"PRODUCTION pubkey fingerprint \(sha256\) = ([0-9a-f]{64})", log)
    assert m, log[-2000:]
    build_fingerprint = m.group(1)
    assert "build-time self-check OK" in log, log[-2000:]
    assert os.path.exists(os.path.join(out_good, "BUILD_PROVENANCE.txt"))

    qemu, serial = boot(os.path.join(out_good, "loader.img"), os.path.join(tmproot, "serial-good.log"), 18930)
    try:
        assert "QEDOS_PRESS_PD: Ed25519 release signature verified" in serial, serial
        _, resp = T.s_client_request(
            b"GET /press/index.html HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n", PQ, timeout=20)
        assert "HTTP/1.1 200 OK" in resp and boot_marker in resp, resp
    finally:
        terminate(qemu)
    ok("PROD_004", "bundle signed by the test production key is accepted and served over TLS1.3")

    # ---- PROD_010: host side and seL4 side agree on the same key's fingerprint ----
    admin_fp = subprocess.run(
        [sys.executable, os.path.join(ROOT, "tools/press-admin.py"),
         "--show-pubkey-fingerprint", "--pubkey-file", prod_pub],
        capture_output=True, text=True, check=True).stdout.strip()
    assert build_fingerprint in admin_fp, (build_fingerprint, admin_fp)
    ok("PROD_010", "press-admin.py's fingerprint for the production pubkey matches the one scripts/build-sel4.sh printed for the identical file")

    # ---- PROD_005: corrupted signature -> rejected by qedos_press_pd itself ----
    out_corrupt = os.path.join(tmproot, "out-corrupt")
    build({"QEDOS_PRESS_PROD": "1", "QEDOS_PRESS_PROD_PUBKEY": prod_pub}, out_corrupt, qpr=bundle_corrupt)
    qemu, serial = boot(os.path.join(out_corrupt, "loader.img"), os.path.join(tmproot, "serial-corrupt.log"), 18931)
    try:
        assert "QEDOS_PRESS_PD: Ed25519 release signature verified" not in serial, serial
        _, resp = T.s_client_request(
            b"GET /press/index.html HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n", PQ, timeout=20)
        assert "HTTP/1.1 503" in resp or "HTTP/1.1 404" in resp, resp
        assert boot_marker not in resp, resp
    finally:
        terminate(qemu)
    ok("PROD_005", "a corrupted (bit-flipped) signature is rejected by qedos_press_pd itself, inside the booted image")

    # ---- PROD_006: validly signed by a DIFFERENT key -> rejected by qedos_press_pd ----
    out_other = os.path.join(tmproot, "out-other")
    build({"QEDOS_PRESS_PROD": "1", "QEDOS_PRESS_PROD_PUBKEY": prod_pub}, out_other, qpr=bundle_other_key)
    qemu, serial = boot(os.path.join(out_other, "loader.img"), os.path.join(tmproot, "serial-other.log"), 18932)
    try:
        assert "QEDOS_PRESS_PD: Ed25519 release signature verified" not in serial, serial
        _, resp = T.s_client_request(
            b"GET /press/index.html HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n", PQ, timeout=20)
        assert boot_marker not in resp, resp
    finally:
        terminate(qemu)
    ok("PROD_006", "a bundle validly signed by a DIFFERENT test keypair is rejected by qedos_press_pd itself")

    # ---- PROD_007: dev-key-signed bundle rejected by a prod-key-configured image ----
    out_devsig = os.path.join(tmproot, "out-devsig")
    build({"QEDOS_PRESS_PROD": "1", "QEDOS_PRESS_PROD_PUBKEY": prod_pub}, out_devsig, qpr=bundle_dev_signed)
    qemu, serial = boot(os.path.join(out_devsig, "loader.img"), os.path.join(tmproot, "serial-devsig.log"), 18933)
    try:
        assert "QEDOS_PRESS_PD: Ed25519 release signature verified" not in serial, serial
        _, resp = T.s_client_request(
            b"GET /press/index.html HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n", PQ, timeout=20)
        assert boot_marker not in resp, resp
    finally:
        terminate(qemu)
    ok("PROD_007", "a bundle signed by the EXISTING DEV key is rejected when the image is configured with a different (production) pubkey -- the dev key cannot work in a production-configured image")

    # ---- PROD_008/009: host-side rollback/replay protection, and persistence across restart ----
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import importlib.util
    spec = importlib.util.spec_from_file_location("press_admin", os.path.join(ROOT, "tools/press-admin.py"))
    pa = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(pa)

    last_gen_file = os.path.join(tmproot, "last-gen")
    header = {"release_no": 10}
    pa.check_and_bump_generation(header, last_gen_file)
    pa.write_generation(last_gen_file, 10)
    try:
        pa.check_and_bump_generation({"release_no": 5}, last_gen_file)
        raise AssertionError("expected rollback rejection for generation 5 <= 10")
    except pa.BundleRejected as e:
        assert "rollback/replay rejected" in str(e)
    try:
        pa.check_and_bump_generation({"release_no": 10}, last_gen_file)
        raise AssertionError("expected rejection for re-using the exact same generation number")
    except pa.BundleRejected:
        pass
    ok("PROD_008", "host-side check_and_bump_generation rejects generation <= last accepted (10), including re-use of the exact same generation number, before any build is attempted")

    # Simulate a host reboot: re-read the SAME last_gen_file in a fresh process-like import --
    # the state is a plain file, not in-memory, so it must survive unchanged.
    spec2 = importlib.util.spec_from_file_location("press_admin2", os.path.join(ROOT, "tools/press-admin.py"))
    pa2 = importlib.util.module_from_spec(spec2)
    spec2.loader.exec_module(pa2)
    try:
        pa2.check_and_bump_generation({"release_no": 7}, last_gen_file)
        raise AssertionError("expected rollback rejection to survive across a simulated restart")
    except pa2.BundleRejected:
        pass
    assert open(last_gen_file).read().strip() == "10"
    ok("PROD_009", "the host-side generation state file survives a press-admin.py process restart (simulating a host reboot) and still rejects the same old generation afterward")

    print(f"\n{len(passed)}/10 PRESS production-key tests passed: {', '.join(passed)}")


if __name__ == "__main__":
    main()
