#!/usr/bin/env python3
"""
Run Viper (Silicon) on the access-control predicates that Microkit exports for every protection domain
(`<image>/viper/<pd>.vpr`: mem_readable / mem_writeable over virtual addresses, capability-slot sets, channel sets)
and discharge, per PD, obligations derived from the system description:

  OBL-MEM-R   forall x. mem_readable(x)  ==> x lies in a region mapped readable in the SDF for this PD
  OBL-MEM-W   forall x. mem_writeable(x) ==> x lies in a region mapped writable in the SDF for this PD
  OBL-NOHW    no TCB / IRQ-handler / I/O-port / vCPU / SMC capability slot, no child PD, no IRQ channel
  OBL-NOTIFY  notify targets are exactly the channel ids declared in the SDF
  OBL-PPC     protected-call targets are exactly the PPC channel ids declared in the SDF
  SANITY-*    each mapped region's first and last byte ARE readable (so the obligations are not vacuous)
  NEG-*       a deliberately false claim (a neighbouring unmapped byte is readable) must FAIL to verify

The .vpr files are produced by the Microkit tool from the same SDF, so this checks the exporter's output against an
independently written obligation set; it does not prove the exporter, the initialiser, or the kernel correct.
Everything is decided by Silicon+Z3 (no Python reasoning about the logic). Exit 0 only if every positive obligation
verifies AND every negative control is refuted. If Viper is not installed the result is SKIPPED (exit 2), never PASS.
"""
import json, os, re, subprocess, sys, tempfile, xml.etree.ElementTree as ET
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
VIPER = os.environ.get("VIPER_HOME", os.path.join(ROOT, "third_party/viper"))


def silicon_cmd():
    jars = sorted(f for f in os.listdir(os.path.join(VIPER, "backends")) if f.endswith(".jar"))
    cp = ":".join(os.path.join(VIPER, "backends", j) for j in jars)
    return ["java", "-Xss128m", "-cp", cp, "viper.silicon.SiliconRunner", "--z3Exe", os.path.join(VIPER, "z3/bin/z3")]


def verify(path):
    p = subprocess.run(silicon_cmd() + [path], capture_output=True, text=True, timeout=300)
    out = p.stdout + p.stderr
    return ("finished verification successfully" in out), out


def parse_sdf(path):
    root = ET.parse(path).getroot()
    mrs = {m.attrib["name"]: int(m.attrib["size"], 0) for m in root.findall("memory_region")}
    pds = {}
    for pd in root.findall("protection_domain"):
        maps = []
        for m in pd.findall("map"):
            va = int(m.attrib["vaddr"].replace("_", ""), 0)
            maps.append((m.attrib["mr"], va, mrs[m.attrib["mr"]], m.attrib["perms"]))
        pds[pd.attrib["name"]] = {"maps": maps, "irqs": len(pd.findall("irq")), "children": len(pd.findall("protection_domain"))}
    chans = {n: {"notify": set(), "ppc": set()} for n in pds}
    for ch in root.findall("channel"):
        ends = ch.findall("end")
        for i, e in enumerate(ends):
            o = ends[1 - i]
            # a PD may notify via its own channel id unless notify="false"; it may PPC if pp="true" on ITS end
            if e.attrib.get("notify", "true") != "false":
                chans[e.attrib["pd"]]["notify"].add(int(e.attrib["id"]))
            if e.attrib.get("pp", "false") == "true":
                chans[e.attrib["pd"]]["ppc"].add(int(e.attrib["id"]))
    return pds, chans


def region_pred(ranges):
    if not ranges:
        return "false"
    return " || ".join(f"({lo} <= x && x < {hi})" for lo, hi in ranges)


def load_vpr(path):
    """The Microkit exporter names memory-region predicates after the region, and sDDF regions contain '/'
    (e.g. mem_generic/serial/queue/...): not a legal Viper identifier, so those files do not parse as emitted
    (finding recorded in docs/HARDENING_RESULTS.md). Renaming '/' to '_' inside identifiers is the only change made."""
    out = []
    for line in open(path):
        if "mem_" in line:
            line = re.sub(r"(?<=[A-Za-z0-9_])/(?=[A-Za-z0-9_])", "_", line)
        out.append(line)
    return "".join(out)


def build_program(pd, info, chan, vpr):
    rd = [(va, va + size) for _, va, size, perms in info["maps"] if "r" in perms]
    wr = [(va, va + size) for _, va, size, perms in info["maps"] if "w" in perms]
    nt, pp = sorted(chan["notify"]), sorted(chan["ppc"])
    inset = lambda s: " || ".join(f"c == {i}" for i in s) if s else "false"
    L = [load_vpr(vpr), "", "// ---- obligations (generated by scripts/viper-capability.py) ----"]
    L.append(f"method obl_mem_r() ensures true {{ assert forall x: Int :: mem_readable(x) ==> ({region_pred(rd)}) }}")
    L.append(f"method obl_mem_w() ensures true {{ assert forall x: Int :: mem_writeable(x) ==> ({region_pred(wr)}) }}")
    L.append("method obl_nohw() ensures true {")
    for pred in ("pansel4_has_tcb_cap", "pansel4_has_irq_handler_cap", "pansel4_has_ioport_cap", "pansel4_has_vcpu_cap", "pansel4_has_arm_smc_cap"):
        if pd in NO_HW_EXCEPT and pred in NO_HW_EXCEPT[pd]:
            continue
        L.append(f"  assert forall c: Int :: !{pred}(c)")
    if info["irqs"] == 0:
        L.append("  assert forall c: Int :: !mk_is_irq_channel(c)")
    if info["children"] == 0:
        L.append("  assert forall c: Int :: !mk_is_child(c)")
    L.append("}")
    L.append(f"method obl_notify() ensures true {{ assert forall c: Int :: mk_is_notify_target(c) ==> ({inset(nt)}) }}")
    L.append(f"method obl_ppc() ensures true {{ assert forall c: Int :: mk_is_ppcall_target(c) ==> ({inset(pp)}) }}")
    L.append("method sanity() ensures true {")
    for _, va, size, perms in info["maps"]:
        if "r" in perms:
            L.append(f"  assert mem_readable({va}) && mem_readable({va + size - 1})")
        if "w" in perms:
            L.append(f"  assert mem_writeable({va}) && mem_writeable({va + size - 1})")
    L.append("}")
    return "\n".join(L) + "\n"


# PDs that legitimately own hardware authority (the obligation is about WHICH ones, so list them explicitly)
NO_HW_EXCEPT = {
    "ethernet_driver": {"pansel4_has_irq_handler_cap", "pansel4_has_ioport_cap"},
    "serial_driver": {"pansel4_has_ioport_cap"},
    "timer_driver": {"pansel4_has_irq_handler_cap"},
}


def negative_control(pd, info, vpr):
    """A false claim about the first readable region: 'the byte just past its end is readable'. Must be refuted."""
    rd = [(va, va + size) for _, va, size, perms in info["maps"] if "r" in perms]
    if not rd:
        return None
    end = max(hi for _, hi in rd)
    for lo, hi in sorted(rd):
        if hi == end:
            return load_vpr(vpr) + f"\nmethod neg() ensures true {{ assert mem_readable({end}) }}\n"
    return None


def run_pd(args):
    pd, info, chan, vpr, outdir = args
    prog = os.path.join(outdir, f"{pd}.obligations.vpr")
    open(prog, "w").write(build_program(pd, info, chan, vpr))
    ok, log = verify(prog)
    res = {"pd": pd, "positive_verified": ok, "log_tail": log.strip().splitlines()[-4:]}
    neg = negative_control(pd, info, vpr)
    if neg is not None:
        npth = os.path.join(outdir, f"{pd}.negative.vpr")
        open(npth, "w").write(neg)
        nok, nlog = verify(npth)
        res["negative_control_refuted"] = not nok and "Assert might fail" in nlog
    return res


def main():
    img = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build/sel4-script"))
    if not os.path.exists(os.path.join(VIPER, "backends/silicon.jar")):
        print("SKIPPED: Viper not installed (third_party/viper); this is NOT a pass"); return 2
    if subprocess.run(["java", "-version"], capture_output=True).returncode != 0:
        print("SKIPPED: java missing"); return 2
    pds, chans = parse_sdf(os.path.join(img, "proofgate.system"))
    outdir = os.path.join(ROOT, "build", "viper-obligations", os.path.basename(img))
    os.makedirs(outdir, exist_ok=True)
    jobs = []
    for pd, info in pds.items():
        vpr = os.path.join(img, "viper", f"{pd}.vpr")
        if not os.path.exists(vpr):
            print(f"FAIL: missing {vpr}"); return 1
        jobs.append((pd, info, chans[pd], vpr, outdir))
    with ThreadPoolExecutor(int(os.environ.get("JOBS", "6"))) as ex:
        results = list(ex.map(run_pd, jobs))
    bad = [r for r in results if not r["positive_verified"] or r.get("negative_control_refuted") is False]
    for r in results:
        print(("PASS " if r not in bad else "FAIL ") + f"{r['pd']}: obligations verified={r['positive_verified']}"
              f" negative-control-refuted={r.get('negative_control_refuted', 'n/a')}")
    json.dump(results, open(os.path.join(outdir, "result.json"), "w"), indent=1)
    print(("VIPER CAPABILITY OBLIGATIONS: PASS" if not bad else "VIPER CAPABILITY OBLIGATIONS: FAIL"), f"({len(results)} PDs, image {img})")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
